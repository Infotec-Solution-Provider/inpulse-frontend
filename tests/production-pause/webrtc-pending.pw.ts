import { test, expect } from "@playwright/test";
test("Odim534 WebRTC404 keeps CRM, WhatsApp and global pause usable without SIP or app teardown",async({page})=>{
 await page.setViewportSize({width:1280,height:1000});
 const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message));
 await page.goto("/tests/production-pause/index.html?odim&user=534&show-phone&webrtc-unconfigured");
 const bar=page.getByRole("region",{name:"Pausa do operador"});
 await expect(bar).toBeVisible({timeout:20000});
 await expect(page.getByTestId("capabilities")).toHaveText('{"operator":true,"telephony":true,"crm":true,"whatsapp":true}');
 await page.getByLabel("Message draft",{exact:true}).fill("Preserved while WebRTC awaits configuration");
 await page.getByRole("button",{name:"Conectar telefonia",exact:true}).click();
 await expect(page.getByTestId("connection")).toHaveText("error");
 await expect(page.getByRole("status",{name:"Sem conexão",exact:true})).toBeVisible();
 await expect(page.getByRole("region",{name:"Telefone web"}).getByRole("alert")).toContainText("configuração WebRTC e SIP");
 await expect(page.getByLabel("Message draft",{exact:true})).toHaveValue("Preserved while WebRTC awaits configuration");
 await expect(page.getByTestId("readonly")).toHaveText("false");
 expect(await page.evaluate(()=>({reads:(window as any).phoneHarness.webrtcReads,registrations:(window as any).phoneHarness.uaStarts,invites:(window as any).phoneHarness.calls.length}))).toEqual({reads:1,registrations:0,invites:0});
 await page.screenshot({path:test.info().outputPath("odim534-webrtc-unconfigured.png"),fullPage:true});
 await bar.getByRole("button",{name:"Pausar",exact:true}).click();
 const dialog=page.getByRole("dialog",{name:"Pausa",exact:true});
 await dialog.getByRole("combobox",{name:"Motivo da pausa"}).click();
 await page.getByRole("option",{name:"Café",exact:true}).click();
 await dialog.getByRole("button",{name:"Pausar agora",exact:true}).click();
 await expect(bar.getByText("Em pausa",{exact:true})).toBeVisible();
 await page.getByRole("button",{name:"Send fixture",exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>(window as any).productionFixture.state.sends.length)).toBe(1);
 await page.evaluate(()=>(window as any).productionFixture.resolveSend());
 await bar.getByRole("button",{name:"Retomar",exact:true}).click();
 await expect(bar.getByText("Disponível",{exact:true})).toBeVisible();
 await page.evaluate(()=>(window as any).productionFixture.navigate("/odim/crm-customers/41"));
 await expect(page.getByRole("heading",{name:"/odim/crm-customers/41",exact:true})).toBeVisible();
 await expect(bar).toBeVisible();
 expect(await page.evaluate(()=>(window as any).phoneHarness.calls.length)).toBe(0);
 expect(errors).toEqual([]);
});
